#!/usr/bin/env node
// Write docs/specs/skill-index.md: one row per skill sorted by slug.
// --check diffs against the file on disk and exits 1 on drift.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { ROOT, loadCatalog, skillRows } from "./plugin-surfaces.mjs";

const check = process.argv.includes("--check");
const catalog = loadCatalog();

const rows = [];
for (const entry of catalog.entries)
  for (const slug of skillRows(entry))
    rows.push({ slug, plugin: entry.id, category: entry.category });
rows.sort((a, b) => (a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0));

const lines = [
  "<!-- generated by scripts/render-skill-index.mjs; do not edit by hand -->",
  "| Skill | Plugin | Category |",
  "|---|---|---|",
];
for (const r of rows) lines.push(`| ${r.slug} | ${r.plugin} | ${r.category} |`);
const output = `${lines.join("\n")}\n`;

const relative = "docs/specs/skill-index.md";
const path = join(ROOT, relative);

if (check) {
  let current = null;
  try {
    current = readFileSync(path, "utf8");
  } catch {
    current = null;
  }
  if (current !== output) {
    process.stderr.write(`skill index drifted: ${relative}\nrun: just render\n`);
    process.exit(1);
  }
  process.stdout.write(`skill index matches (${rows.length} skills)\n`);
} else {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, output);
  process.stdout.write(`wrote ${relative} (${rows.length} skills)\n`);
}
